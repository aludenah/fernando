import {readFile,writeFile} from 'node:fs/promises';
import {progressCatalog} from '../docs/sync-protocol.js';
const root=new URL('../',import.meta.url),catalogs={};
for(const [id,file] of [['fernando','course'],['josue','josue-course']]){
  catalogs[id]=progressCatalog(JSON.parse(await readFile(new URL(`docs/data/${file}.json`,root),'utf8')));
}
const protocol=await readFile(new URL('docs/sync-protocol.js',root),'utf8');
const source='// Generated by scripts/build-progress-service.mjs; do not edit manually.\n'+
  `const SYNC_CATALOGS=${JSON.stringify(catalogs,null,2)};\n\n`+protocol.replace(/^export /gm,'');
const handler=await readFile(new URL('integrations/progress/Code.gs',root),'utf8');
const installer='// INSTALACIÓN: copia todo este archivo en Code.gs de un proyecto NUEVO de Apps Script.\n'+
  '// Esta versión reúne el catálogo y el servicio en un único archivo.\n'+
  '// Guarda solo respuestas y temas repasados. No accede a Drive ni al correo.\n\n'+source+'\n'+handler;
for(const [name,content] of [['Core.gs',source],['Instalar.gs',installer]]){
  const path=new URL(`integrations/progress/${name}`,root);
  if(process.argv.includes('--check')){
    if(await readFile(path,'utf8')!==content)throw new Error(`Regenera ${name} para actualizar el servicio de avance.`);
  }else await writeFile(path,content);
}
