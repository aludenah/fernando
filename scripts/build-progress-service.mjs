import {readFile,writeFile} from 'node:fs/promises';
import {progressCatalog} from '../docs/sync-protocol.js';
const root=new URL('../',import.meta.url),catalogs={};
for(const [id,file] of [['fernando','course'],['josue','josue-course']]){
  catalogs[id]=progressCatalog(JSON.parse(await readFile(new URL(`docs/data/${file}.json`,root),'utf8')));
}
const protocol=await readFile(new URL('docs/sync-protocol.js',root),'utf8');
const source='// Generated by scripts/build-progress-service.mjs; do not edit manually.\n'+
  `const SYNC_CATALOGS=${JSON.stringify(catalogs,null,2)};\n\n`+protocol.replace(/^export /gm,'');
const path=new URL('integrations/progress/Core.gs',root);
if(process.argv.includes('--check')){
  if(await readFile(path,'utf8')!==source)throw new Error('Regenera el catálogo del servicio de avance.');
}else await writeFile(path,source);
