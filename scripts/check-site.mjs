import {readFile,readdir,access} from 'node:fs/promises';
import {resolve,dirname} from 'node:path';
import {fileURLToPath} from 'node:url';
import assert from 'node:assert/strict';
import {validateMatrixCourse,chooseMatrixPractice,matrixRules} from '../docs/matrices.js';
import {math} from '../docs/math.js';
import {activities,landingView,activitiesView} from '../docs/activities.js';
const root=resolve(dirname(fileURLToPath(import.meta.url)),'../docs');
const course=validateMatrixCourse(JSON.parse(await readFile(resolve(root,'data/course.json'),'utf8')));
assert.equal(chooseMatrixPractice(course.matrixPractice.exercises).length,5);
for(const exercise of course.matrixPractice.exercises)math(`\\(a_{ij}=${matrixRules[exercise.rule].tex}\\)`,{strict:true});
const index=await readFile(resolve(root,'index.html'),'utf8');
assert.doesNotMatch(index,/sync-status|script.google|padres/i);
for(const [,path] of index.matchAll(/(?:src|href)="(\.\/[^"#]+)"/g))await access(resolve(root,path.split('?')[0]));
for(const name of await readdir(root)){
 if(!name.endsWith('.js'))continue;
 const source=await readFile(resolve(root,name),'utf8');
 for(const [,path] of source.matchAll(/from\s*['"](\.\/[^'"]+)['"]/g))await access(resolve(root,path.split('?')[0]));
 assert.doesNotMatch(source,/indexedDB|localStorage|sessionStorage|script\.google|createProgressSync|BroadcastChannel|setInterval\(/,name);
}
assert.equal(activities.length,1);assert.equal(activities[0].id,'matrices');
assert.doesNotMatch(landingView()+activitiesView(),/Josué|Padres|avance|progreso/i);
assert.equal((landingView().match(/class="access-card student"/g)||[]).length,1);
assert.match(activitiesView(),/class="activity-card" href="#matrices"/);
const dataFiles=await readdir(resolve(root,'data'));
assert.deepEqual(dataFiles,['course.json']);
for(const path of ['.nojekyll','vendor/report-font/AulaSans.ttf','vendor/report-font/LICENSE','vendor/jspdf/jspdf.umd.min.js','vendor/jspdf/LICENSE'])await access(resolve(root,path));
const expected=await readFile(resolve(root,'../node_modules/jspdf/dist/jspdf.umd.min.js'));
assert.ok(expected.equals(await readFile(resolve(root,'vendor/jspdf/jspdf.umd.min.js'))),'El generador PDF debe coincidir con la versión fijada.');
const css=await readFile(resolve(root,'vendor/katex/katex.min.css'),'utf8');
for(const [,font] of css.matchAll(/url\(([^)]+)\)/g))await access(resolve(root,'vendor/katex',font));
console.log('Sitio comprobado: acceso único de Fernando, catálogo de aplicaciones, cinco matrices y comprobante PDF; sin seguimiento ni almacenamiento de respuestas.');
